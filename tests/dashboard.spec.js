import { test, expect } from '@playwright/test';

test('filters, search, sort, agent profiles, navigation, and export work', async ({page}) => {
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Service performance'})).toBeVisible();
  await expect(page.locator('tbody tr')).toHaveCount(5);
  const originalCases=await page.locator('.metric-value').first().innerText();
  await page.getByLabel('Reporting period').selectOption('7');
  await expect(page.locator('.metric-value').first()).not.toHaveText(originalCases);
  await page.getByLabel('Team',{exact:true}).selectOption('Technical Support');
  await expect(page.locator('tbody tr')).toHaveCount(4);
  await page.getByLabel('Search agents').fill('Lana');
  await expect(page.locator('tbody tr')).toHaveCount(1);
  await page.getByRole('button',{name:'View Lana Steiner',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('heading',{name:'Lana Steiner'})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Search agents').fill('no-such-agent');
  await expect(page.getByRole('heading',{name:'No agents found'})).toBeVisible();
  await page.getByRole('button',{name:'Clear filters'}).click();
  await expect(page.locator('tbody tr')).toHaveCount(5);
  await page.getByLabel('Sort agents').selectOption('qa:false');
  await expect(page.locator('tbody tr').first()).toContainText('Sienna Park');
  await page.getByRole('button',{name:'Next page'}).click();
  await expect(page.locator('.table-pagination')).toContainText('Showing 6–10 of 12 agents');
  await page.getByRole('button',{name:'Agents 12',exact:true}).click();
  await expect(page.locator('tbody tr')).toHaveCount(8);
  await page.getByRole('button',{name:'Quality & advocacy',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Quality & advocacy trends'})).toBeVisible();
  await page.getByRole('button',{name:'Open dashboard guide'}).click();
  await expect(page.getByRole('dialog')).toContainText('Brand advocacy');
  await page.getByRole('button',{name:'Close dialog'}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export report'}).click();
  expect((await downloaded).suggestedFilename()).toBe('relay-performance-7days.csv');
  await expect(page.getByRole('status')).toContainText('Exported 12 agents');
  await page.getByLabel('Reporting period').selectOption('90');
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await expect(page.locator('.date-range')).toContainText('Jul 19');
  expect(errors).toEqual([]);
  await page.screenshot({path:'/tmp/relay-desktop.png',fullPage:true,animations:'disabled'});
});

test('mobile layout fits and navigation works', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Service performance'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Agents 12',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your people, at a glance.'})).toBeVisible();
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('button',{name:'Overview',exact:true}).click();
  await expect(page.locator('.sidebar')).not.toBeInViewport();
  await page.screenshot({path:'/tmp/relay-mobile.png',fullPage:true,animations:'disabled'});
});
